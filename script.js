/* ---------------------------------------------------------------------
   Theme toggle (light / dark) — persists via localStorage,
   falls back to the visitor's system preference on first visit.
--------------------------------------------------------------------- */
function initTheme() {
  const root = document.documentElement;
  const toggle = document.getElementById('theme-toggle');

  const stored = localStorage.getItem('mc-theme');
  const systemPrefersLight = window.matchMedia('(prefers-color-scheme: light)').matches;
  const initial = stored || (systemPrefersLight ? 'light' : 'dark');

  root.setAttribute('data-theme', initial);
  toggle.setAttribute('aria-pressed', String(initial === 'light'));

  toggle.addEventListener('click', () => {
    const next = root.getAttribute('data-theme') === 'dark' ? 'light' : 'dark';
    root.setAttribute('data-theme', next);
    toggle.setAttribute('aria-pressed', String(next === 'light'));
    localStorage.setItem('mc-theme', next);
  });
}

/* ---------------------------------------------------------------------
   Certificates — rendered from window.CERTIFICATES (certificates-data.js,
   generated by scripts/build-certificates.js from whatever is currently
   in /Certificates). The homepage carousel and the certificates.html
   explorer both read from this one list, so they can't drift apart.
--------------------------------------------------------------------- */
const DOC_ICON =
  '<svg class="{cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.6"><path d="M6 2h9l3 3v17H6Z"/><path d="M15 2v3h3"/></svg>';
const IMAGE_ICON =
  '<svg class="{cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.6"><path d="M6 2h9l3 3v17H6Z"/><path d="M15 2v3h3"/><circle cx="10.3" cy="12.3" r="1.2"/><path d="M8 18l2.4-2.8 1.8 2 2.6-3.4L18 18"/></svg>';

function isImageType(ext) {
  return ext === '.jpg' || ext === '.jpeg' || ext === '.png';
}

function certIcon(item, cls) {
  const markup = isImageType(item.ext) ? IMAGE_ICON : DOC_ICON;
  return markup.replace('{cls}', cls);
}

function certHref(item) {
  return `./Certificates/${item.file}`;
}

function certPdfHref(item) {
  return item.pdfFile ? `./Certificates/${item.pdfFile}` : '';
}

function renderCertificates() {
  if (!Array.isArray(window.CERTIFICATES)) return;
  const items = window.CERTIFICATES;

  renderCarousel(items.slice(0, 10));
  renderExplorer(items);
}

function renderCarousel(items) {
  const track = document.getElementById('carousel-track');
  if (!track || !items.length) return;

  track.innerHTML = items
    .map(
      (item) => `
    <a class="cert-card glass shine" href="${certHref(item)}"
       data-preview-src="${certHref(item)}"
       data-preview-type="${isImageType(item.ext) ? 'image' : 'pdf'}"
       data-preview-pdf="${certPdfHref(item)}"
       data-preview-name="${item.pdfFile || ''}">
      <div class="cert-thumb">${certIcon(item, '')}</div>
      <h3 class="cert-title">${item.title}</h3>
      <p class="cert-org">${item.type} · ${item.date}</p>
    </a>`
    )
    .join('');
}

function renderExplorer(items) {
  const table = document.querySelector('.explorer-table');
  const count = document.getElementById('explorer-count');
  if (!table) return;

  const head = table.querySelector('.explorer-head');
  table.querySelectorAll('.explorer-row:not(.explorer-head)').forEach((row) => row.remove());

  const rowsHtml = items
    .map(
      (item) => `
    <a class="explorer-row" href="${certHref(item)}"
       data-preview-src="${certHref(item)}"
       data-preview-type="${isImageType(item.ext) ? 'image' : 'pdf'}"
       data-preview-pdf="${certPdfHref(item)}"
       data-preview-name="${item.pdfFile || ''}">
      <span class="col-name">${certIcon(item, 'file-icon')}${item.title}</span>
      <span class="col-date">${item.date}</span>
      <span class="col-type">${item.type}</span>
      <span class="col-size">${item.size}</span>
    </a>`
    )
    .join('');

  head.insertAdjacentHTML('afterend', rowsHtml);
  if (count) count.textContent = `${items.length} item${items.length === 1 ? '' : 's'}`;
}

/* ---------------------------------------------------------------------
   File preview modal — opens certificate/resume PDFs and images in a
   blurred overlay instead of sending people off to download them.
   Ctrl/Cmd/middle-click still lets a link open normally in a new tab.
--------------------------------------------------------------------- */
function initFileModal() {
  const modal = document.getElementById('file-modal');
  if (!modal) return;
  const body = document.getElementById('file-modal-body');
  const download = document.getElementById('file-modal-download');

  function openModal(src, type, pdfHref, pdfName) {
    body.innerHTML =
      type === 'image'
        ? `<img src="${src}" alt="" />`
        : `<iframe src="${src}" title="Document preview"></iframe>`;

    if (download) {
      if (pdfHref) {
        download.href = pdfHref;
        download.setAttribute('download', pdfName || '');
        download.hidden = false;
      } else {
        download.hidden = true;
        download.removeAttribute('href');
      }
    }

    modal.classList.add('open');
    modal.setAttribute('aria-hidden', 'false');
    document.body.classList.add('modal-open');
  }

  function closeModal() {
    modal.classList.remove('open');
    modal.setAttribute('aria-hidden', 'true');
    document.body.classList.remove('modal-open');
    body.innerHTML = '';
  }

  modal.querySelectorAll('[data-modal-close]').forEach((el) => {
    el.addEventListener('click', closeModal);
  });

  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape' && modal.classList.contains('open')) closeModal();
  });

  document.addEventListener('click', (e) => {
    // let the download link's own click through instead of treating it
    // as a "reopen the modal" trigger
    if (e.target.closest('#file-modal-download')) return;

    const trigger = e.target.closest('[data-preview-src]');
    if (!trigger) return;
    if (e.ctrlKey || e.metaKey || e.shiftKey || e.button === 1) return;
    e.preventDefault();
    openModal(
      trigger.dataset.previewSrc,
      trigger.dataset.previewType,
      trigger.dataset.previewPdf,
      trigger.dataset.previewName
    );
  });
}

