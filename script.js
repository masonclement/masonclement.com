function contactHref() {
  // index.html can jump straight to the section; every other page
  // (404, certificates, under-construction) has to route through it first.
  const onHomePage = /(^|\/)index\.html$/.test(window.location.pathname) ||
    window.location.pathname.endsWith('/');
  return onHomePage ? '#contact' : 'index.html#contact';
}

