function initInfoModal() {
  const modal = document.getElementById('info-modal');
  if (!modal) return;
  const icon = document.getElementById('info-modal-icon');
  const title = document.getElementById('info-modal-title');
  const text = document.getElementById('info-modal-text');
  const link = document.getElementById('info-modal-link');

  function openModal(key) {
    const content = INFO_MODAL_CONTENT[key];
    if (!content) return;

    icon.innerHTML = content.icon;
    title.textContent = content.title;
    text.textContent = content.text;

    if (content.linkHref) {
      link.href = content.linkHref();
      link.textContent = content.linkText;
      link.hidden = false;
    } else {
      link.hidden = true;
      link.removeAttribute('href');
    }

    modal.classList.add('open');
    modal.setAttribute('aria-hidden', 'false');
    document.body.classList.add('modal-open');
  }

  function closeModal() {
    modal.classList.remove('open');
    modal.setAttribute('aria-hidden', 'true');
    document.body.classList.remove('modal-open');
  }

  modal.querySelectorAll('[data-modal-close]').forEach((el) => {
    el.addEventListener('click', closeModal);
  });

  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape' && modal.classList.contains('open')) closeModal();
  });

  document.addEventListener('click', (e) => {
    const trigger = e.target.closest('[data-info-modal]');
    if (!trigger) return;
    e.preventDefault();
    openModal(trigger.dataset.infoModal);
  });
}

/* ---------------------------------------------------------------------
   Scroll reveal — fades/slides sections in as they enter the viewport.
--------------------------------------------------------------------- */
function initScrollReveal() {
  const items = document.querySelectorAll('.reveal');
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('in-view');
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.1, rootMargin: '0px 0px -10% 0px' });

  items.forEach(item => observer.observe(item));
}

/* ---------------------------------------------------------------------
   Timeline — click/tap (or Enter/Space) to expand a milestone.
   Only one item open at a time keeps the section tidy.
--------------------------------------------------------------------- */
function initTimeline() {
  const items = document.querySelectorAll('.timeline-content');

  items.forEach(item => {
    item.addEventListener('click', () => {
      const isOpen = item.getAttribute('aria-expanded') === 'true';

      items.forEach(other => other.setAttribute('aria-expanded', 'false'));
      item.setAttribute('aria-expanded', String(!isOpen));
    });
  });
}

/* ---------------------------------------------------------------------
   About bio — collapsed by default with a "Read More" toggle.
--------------------------------------------------------------------- */
function initBioToggle() {
  const wrap = document.getElementById('bio-wrap');
  const btn = document.getElementById('bio-toggle');
  if (!wrap || !btn) return;

  const collapsedHeight = 220;
  wrap.style.maxHeight = collapsedHeight + 'px';

  btn.addEventListener('click', () => {
    const expanding = !wrap.classList.contains('expanded');

    if (expanding) {
      wrap.classList.add('expanded');
      wrap.style.maxHeight = wrap.scrollHeight + 'px';
      wrap.addEventListener('transitionend', function onEnd(e) {
        if (e.propertyName !== 'max-height') return;
        wrap.removeEventListener('transitionend', onEnd);
        if (wrap.classList.contains('expanded')) {
          wrap.style.maxHeight = 'none';
        }
      });
    } else {
      // pin the current (auto) height first so the shrink has a real
      // pixel value to transition from, then collapse on the next frame
      wrap.style.maxHeight = wrap.scrollHeight + 'px';
      requestAnimationFrame(() => {
        requestAnimationFrame(() => {
          wrap.classList.remove('expanded');
          wrap.style.maxHeight = collapsedHeight + 'px';
        });
      });
    }

    btn.setAttribute('aria-expanded', String(expanding));
    btn.textContent = expanding ? 'Read Less' : 'Read More';
  });
}

/* ---------------------------------------------------------------------
   Certificate carousel — infinite loop (wraps from last back to first
   and vice versa), with buttons, dots, and swipe support.
--------------------------------------------------------------------- */
function initCarousel() {
  const track = document.getElementById('carousel-track');
  const dotsWrap = document.getElementById('carousel-dots');
  const prevBtn = document.querySelector('.carousel-btn.prev');
  const nextBtn = document.querySelector('.carousel-btn.next');
  if (!track || !dotsWrap || !prevBtn || !nextBtn) return;

  const cards = Array.from(track.children);
  if (!cards.length) return;

  let index = 0;
  let visibleCount = getVisibleCount();

  // Build dots
  cards.forEach((_, i) => {
    const dot = document.createElement('button');
    dot.setAttribute('aria-label', `Go to certificate ${i + 1}`);
    dot.addEventListener('click', () => goTo(i));
    dotsWrap.appendChild(dot);
  });
  const dots = Array.from(dotsWrap.children);

  function getVisibleCount() {
    const viewportWidth = track.parentElement.offsetWidth;
    const cardWidth = cards[0].getBoundingClientRect().width + 20; // + gap
    return Math.max(1, Math.floor(viewportWidth / cardWidth));
  }

  function update() {
    const cardWidth = cards[0].getBoundingClientRect().width + 20;
    track.style.transform = `translateX(-${index * cardWidth}px)`;
    dots.forEach((d, i) => d.classList.toggle('active', i === index));
  }

  function goTo(i) {
    const max = cards.length - 1;
    if (i > max) index = 0;          // wrap to first
    else if (i < 0) index = max;     // wrap to last
    else index = i;
    update();
  }

  prevBtn.addEventListener('click', () => goTo(index - 1));
  nextBtn.addEventListener('click', () => goTo(index + 1));

  // Swipe support
  let touchStartX = 0;
  track.addEventListener('touchstart', (e) => {
    touchStartX = e.touches[0].clientX;
  }, { passive: true });
  track.addEventListener('touchend', (e) => {
    const diff = e.changedTouches[0].clientX - touchStartX;
    if (diff > 40) goTo(index - 1);
    else if (diff < -40) goTo(index + 1);
  }, { passive: true });

  window.addEventListener('resize', () => {
    visibleCount = getVisibleCount();
    update();
  });

  update();
}
